"""候选反应模板库，供数据驱动的 expert 池设计使用。

为什么要这个文件
----------------
findings §12 测出 routing 收益随 action 空间有效维度单调上升（斜率 +0.0017
HV/维），§14 又测出在 2.20 维的池子上学出来的 router 打不过一条零参数的
单 expert 基线。两条合起来给出一个可证伪的设计任务：**把池子的有效维度推高，
看 routing 收益会不会落到那条线上**。

`src/editors.py` 里原来的四个池是按化学直觉手写的，并集只有 40 条模板，
而且 gsk3b / jnk3 两个池都是"往芳环 CH 上挂取代基"，方向天然重合。
这里把候选模板扩到 ~80 条，再由 `scripts/profile_templates.py` 实测每条模板
在四个目标上的平均效果，按**选择性**分配给四个 expert —— 让"谁属于哪个 expert"
由数据定，而不是由我们对激酶药化的猜测定。

约束：env 强制保留 Bemis-Murcko 骨架，所以这里只放**取代基级别**的编辑。
改环系的模板产物一律会被判不合格，白白消耗 generation 预算。

模板分成几族，每族内部方向相近、族之间尽量不同，这样聚类才有东西可分：
极性增 / 疏水增 / 卤素 / 体积减 / 杂原子互换 / 链长 / 氢键给体受体翻转。
"""
from __future__ import annotations

# --- 极性 / 氢键：往芳环上挂能给受氢键的小基团 --------------------------
POLAR_ADD = [
    "[cH:1]>>[c:1]N",
    "[cH:1]>>[c:1]O",
    "[cH:1]>>[c:1]C(N)=O",
    "[cH:1]>>[c:1]NC(C)=O",
    "[cH:1]>>[c:1]C#N",
    "[cH:1]>>[c:1]S(N)(=O)=O",
    "[cH:1]>>[c:1]N1CCNCC1",
    "[cH:1]>>[c:1]NC(N)=O",
    "[cH:1]>>[c:1]C(=O)O",
    "[cH:1]>>[c:1]NS(C)(=O)=O",
    "[cH:1]>>[c:1]C(=O)N(C)C",
    "[cH:1]>>[c:1]NCCO",
    "[cH:1]>>[c:1]C(=O)NO",
    "[cH:1]>>[c:1]N1CCOCC1",
]

# --- 疏水 / 体积：烷基、环烷、芳基 ---------------------------------------
HYDROPHOBIC_ADD = [
    "[cH:1]>>[c:1]SC",
    "[cH:1]>>[c:1]C(C)C",
    "[cH:1]>>[c:1]C(C)(C)C",
    "[cH:1]>>[c:1]OCC",
    "[cH:1]>>[c:1]C1CC1",
    "[cH:1]>>[c:1]C1CCCCC1",
    "[cH:1]>>[c:1]CC",
    "[cH:1]>>[c:1]OCCC",
    "[cH:1]>>[c:1]SCC",
]

# --- 卤素 / 氟化：药化里和疏水是两回事（电子效应不同）-------------------
HALOGEN = [
    "[cH:1]>>[c:1]F",
    "[cH:1]>>[c:1]Cl",
    "[cH:1]>>[c:1]Br",
    "[cH:1]>>[c:1]C(F)(F)F",
    "[cH:1]>>[c:1]OC(F)(F)F",
    "[cH:1]>>[c:1]C(F)F",
    "[cH:1]>>[c:1]OCF",
    "[cH:1]>>[c:1]SC(F)(F)F",
]

# --- 删除 / 缩小：对任意带环分子都能触发 --------------------------------
SHRINK = [
    "[R:1][!R;D1]>>[R:1]",
    "[c:1][C;!R;H3]>>[c:1]",
    "[c:1][F,Cl,Br,I]>>[c:1]",
    "[c:1]C(F)(F)F>>[c:1]C",
    "[c:1]S(N)(=O)=O>>[c:1]",
    "[c:1][N+](=O)[O-]>>[c:1]",
    "[c:1]C#N>>[c:1]C",
    "[c:1]OC(F)(F)F>>[c:1]OC",
    "[C;!R;H2:1][C;!R;H3]>>[C;!R;H3:1]",
    "[c:1][O;!R][CH3]>>[c:1]O",
    "[c:1]C(C)(C)C>>[c:1]C(C)C",
    "[c:1][N;!R]([CH3])[CH3]>>[c:1]N([CH3])",
    "[c:1]C(=O)OC>>[c:1]C(=O)O",
    "[c:1]S(C)(=O)=O>>[c:1]C",
]

# --- 小基团增长：QED 偏轻时用 ------------------------------------------
GROW = [
    "[cH:1]>>[c:1]OC",
    "[cH:1]>>[c:1]C",
    "[cH:1]>>[c:1]CO",
    "[cH:1]>>[c:1]CN",
    "[cH:1]>>[c:1]CC(=O)O",
    "[cH:1]>>[c:1]CCO",
]

# --- 等价替换：换原子不换大小，和增删是两个方向 --------------------------
SWAP = [
    "[c:1]Br>>[c:1]F",
    "[c:1]I>>[c:1]Cl",
    "[c:1][N+](=O)[O-]>>[c:1]N",
    "[c:1][O;!R][CH3]>>[c:1][N;!R][CH3]",
    "[c:1][S;!R][CH3]>>[c:1][O;!R][CH3]",
    "[c:1]C(=O)[OH]>>[c:1]C(=O)N",
    "[c:1]C(=O)N>>[c:1]C#N",
    "[c:1]Cl>>[c:1]C",
    "[c:1]F>>[c:1]O",
    "[c:1][NH2]>>[c:1][OH]",
    "[c:1][OH]>>[c:1][NH2]",
    "[C;!R:1](=O)[OH]>>[C;!R:1](=O)OC",
]

# --- 氢键给体 <-> 受体翻转：对 QED 的 HBD/HBA 项最直接 -------------------
HBOND_FLIP = [
    "[c:1][NH2]>>[c:1]N(C)C",
    "[c:1][OH]>>[c:1]OC",
    "[c:1]C(=O)[NH2]>>[c:1]C(=O)N(C)C",
    "[c:1][NH]C(C)=O>>[c:1]N(C)C(C)=O",
    "[c:1]OC>>[c:1][OH]",
    "[c:1]N(C)C>>[c:1][NH2]",
]

# --- 链长：不改元素组成的拓扑调整 ---------------------------------------
CHAIN = [
    "[c:1][CH3]>>[c:1]CC",
    "[c:1][CH2][CH3]>>[c:1]CCC",
    "[c:1][O;!R][CH3]>>[c:1][O;!R]CC",
    "[c:1][CH2][CH2][CH3]>>[c:1]CC",
]

FAMILIES = {
    "polar_add": POLAR_ADD,
    "hydrophobic_add": HYDROPHOBIC_ADD,
    "halogen": HALOGEN,
    "shrink": SHRINK,
    "grow": GROW,
    "swap": SWAP,
    "hbond_flip": HBOND_FLIP,
    "chain": CHAIN,
}

# 去重后的全部候选模板。族只是书写上的分组，设计时不使用 ——
# 用了就等于又把人的先验塞回去了，那正是这次要替换掉的东西。
ALL_TEMPLATES = sorted({s for fam in FAMILIES.values() for s in fam})

FAMILY_OF = {}
for _fam, _lst in FAMILIES.items():
    for _s in _lst:
        FAMILY_OF.setdefault(_s, _fam)
